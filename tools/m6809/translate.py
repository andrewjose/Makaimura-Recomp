"""
Name:        translate.py
Description: the 6809 program translated into C an instruction at a time, timed as MAME's core times it: the
             translation scaffold (milestone M4), run by the board's runtime (runtime/src/m6809.c)
Version:     0.1.0
Created:     19-11-2026

license:BSD-3-Clause
    python tools/m6809/translate.py [--rom PATH ...]

Writes build/generated/program/: program.h, program_NN.c and entries.c. Nothing it writes may be redistributed:
it is the game's code, translated from the user's own ROM.

The program is what the static analysis finds (tools/m6809/analysis.py, symbols.txt, its overlays: no traces).
Every instruction becomes the C of its IR (tools/m6809/lift.py, written by the core's printer, v60/emit_c.py,
with this CPU's names), so the C does what MAME's MC6809 core does; the board's time (cpu.cycles) is set before
each data access to the end of its bus cycle, as MAME's core has it there, and to the instruction's end after it.

The code is split into regions, each a C function: from each entry, the code its branches and jumps reach,
which no region before it took. A region is entered at any of its instructions (a switch), and gives back the
address execution goes on at when it leaves: a call (the return address is on the 6809's stack, as the
statements pushed it), a return (the address the statements pulled), a jump through a register, a jump into
another region, or into the banked window from outside it (the bank is the runtime's: the latch's at the time).
The runtime's trampoline (m6809_run) dispatches that address to its region, so the program's own stack is the
only one: whatever it does with it (a routine that drops its return address, a return through a table) is what
the board does.

After each instruction, M6809_CHECK(next) lets the board's time catch up (the VBLANK) and takes an interrupt
the line holds, if the mask lets it through, before the next instruction: its state pushed, the region leaves for
its handler (m6809_event), and its RTI goes on at whatever the stack gives (the program switches tasks in its
IRQ: a handler need not come back where it was taken). SYNC and CWAI wait in the runtime (m6809_sync,
m6809_cwai: CWAI then leaves for the handler).
"""
import argparse
import importlib.util
import os
import sys
from collections import deque

TOOLS = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ROOT = os.path.dirname(TOOLS)
sys.path.insert(0, TOOLS)

import makaimura_rom as rom                      # noqa: E402
import symbols                                   # noqa: E402
from m6809 import analysis                       # noqa: E402
from m6809 import lift                           # noqa: E402
from m6809.lift import ir                        # noqa: E402
from v60 import emit_c                           # noqa: E402  (the core's C printer)

OUT = os.path.join(ROOT, "build", "generated", "program")
REGIONS_PER_FILE = 60
WINDOW = (0x4000, 0x6000)
HEADER = """/*
 * Generated by tools/m6809/translate.py from the user's own ROM. Do not redistribute.
 * Makaimura (makaimurg): the MC6809 program translated to C.
 */
"""
# Fair Knight (runtime/src/fair_knight.c, docs/fair-knight/): hand-written C called before the instruction at
# each of these addresses of the fixed ROM. A hook gives back 0 (the instruction runs) or the address to go on at.
# With its option off a hook changes nothing, so the program stays the board's.
FAIR_KNIGHT_HOOKS = {
    0x9984: "fk_hook_9984",   # the hit's invincibility (STB <$AD)
    0x9A39: "fk_hook_9A39",   # the hit's hop direction (knockback)
    0x93CA: "fk_hook_93CA",   # the jump state's direction (air control)
}
REGISTER_NAMES = ("cpu.a", "cpu.b", "cpu.dp", "cpu.x", "cpu.y", "cpu.u", "cpu.s")
FLAG_NAMES = {"e": "cpu.fe", "f": "cpu.ff", "h": "cpu.fh", "i": "cpu.fi", "s": "cpu.fn", "z": "cpu.fz",
              "ov": "cpu.fv", "cy": "cpu.fc"}


class Names(emit_c.Names):
    def register(self, index):
        return REGISTER_NAMES[index]

    def flag(self, name):
        return FLAG_NAMES[name]


class Printer(emit_c.Printer):
    def __init__(self):
        super().__init__(Names())

    def effect(self, node):
        if node.name == "rti_entire_state":
            return f"if (!({self.expr(node.args[0])})) m6809_fault(\"RTI of a frame without E\", cpu_pc);"
        raise ValueError(f"unknown effect {node.name}")


def in_window(address):
    return WINDOW[0] <= address < WINDOW[1]


def load_code(paths):
    spec = importlib.util.spec_from_file_location("disassemble", os.path.join(TOOLS, "disassemble.py"))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    program = rom.load_program(paths)
    syms = symbols.load(os.path.join(ROOT, "symbols.txt"))
    ram_code = syms.ram_code(program)
    entries = module.vector_entries(program) + [(s.bank, s.address, s.name) for s in syms.code()]
    code = analysis.explore(program, entries, syms.tables(), syms.no_return(), ram_code)
    return program, syms, code, ram_code


def name_of(key):
    bank, address = key
    return f"r_{address:04X}" if bank is None else f"r_{bank}_{address:04X}"


def label_of(key):
    bank, address = key
    return f"L_{address:04X}" if bank is None else f"L_{bank}_{address:04X}"


def hex16(value):
    return f"0x{value & 0xFFFF:04X}u"


class Translator:
    def __init__(self, code):
        self.code = code
        self.instructions = code.instructions
        self.lifted = {}
        self.unsupported = {}
        for key, instruction in self.instructions.items():
            try:
                self.lifted[key] = lift.lift(instruction, prefix="t_")
            except lift.Unsupported as problem:
                self.unsupported[key] = str(problem)
        self.bank_writers = {analysis.key(bank, ins.address) for bank, ins, _ in code.bank_switches}
        # the bank each key's instruction runs in (the window's own; None outside it)
        self.regions = self.split()

    def successor(self, key, address):
        """The key of the instruction at 'address' that follows the one at 'key', if it is reached without the
        runtime (a goto): in the window only from the window, in the same bank, and not after a write of the
        bank latch; None when the runtime must dispatch it"""
        bank, _ = key
        if in_window(address):
            if bank is None or key in self.bank_writers:
                return None
            target = (bank, address)
        else:
            target = analysis.key(None, address)
        return target if target in self.instructions else None

    def local_successors(self, key):
        """The instructions the one at 'key' goes on to without leaving its region (calls' return points too)"""
        instruction = self.instructions[key]
        flow = instruction.flow
        result = []
        if flow in ("next", "branch", "call", "icall", "wait", "swi"):
            result.append(instruction.next)
        if flow in ("branch", "jump") and instruction.target is not None:
            result.append(instruction.target)
        keys = []
        for address in result:
            target = self.successor(key, address & 0xFFFF)
            if target is not None:
                keys.append(target)
        return keys

    def split(self):
        """Regions: from each entry in order (the vectors, the calls' targets, the tables' and the symbols'
        entries, then whatever is left), the instructions its local flow reaches that no region took"""
        owner = {}
        regions = {}
        order = lambda k: (-1 if k[0] is None else k[0], k[1])    # noqa: E731
        starts = sorted(self.code.entries, key=order) + sorted(self.instructions, key=order)
        for start in starts:
            if start in owner or start not in self.instructions:
                continue
            body = []
            work = deque([start])
            while work:
                key = work.popleft()
                if key in owner:
                    continue
                owner[key] = start
                body.append(key)
                work.extend(k for k in self.local_successors(key) if k not in owner)
            regions[start] = sorted(body, key=order)
        self.owner = owner
        return regions

    # ---- C ----

    def transfer(self, region, key, address):
        """C that sends execution to 'address' after the instruction at 'key': a goto inside the region, or the
        address given back to the trampoline"""
        target = self.successor(key, address)
        if target is not None and self.owner.get(target) == region:
            return f"goto {label_of(target)};"
        return f"return {hex16(address)};"

    def instruction_lines(self, region, key):
        instruction = self.instructions[key]
        address = instruction.address
        if key in self.unsupported:
            return [f"m6809_fault(\"{self.unsupported[key]}\", {hex16(address)});", f"return {hex16(address)};"]
        lifter = self.lifted[key]
        printer = Printer()
        lines = [f"cpu_pc = {hex16(address)};"] if any(isinstance(s, ir.Effect) for s in lifter.statements) else []
        hook = FAIR_KNIGHT_HOOKS.get(address) if key[0] is None else None
        if hook:
            lines = [f"{{ const uint16_t fk_next_ = {hook}(); if (fk_next_) return fk_next_; }}"] + lines
        data = [access for access in lifter.accesses if access.kind in ("R", "W")]
        counted = 0
        position = 0
        masks = False
        for statement in lifter.statements:
            is_access = isinstance(statement, ir.Store) or (isinstance(statement, ir.SetTemp) and
                                                          isinstance(statement.value, ir.Load))
            if is_access:
                # the board's time at this access: the end of its bus cycle
                at = data[position].cycle + 1
                position += 1
                if at > counted:
                    lines.append(f"cpu.cycles += {at - counted};")
                    counted = at
            if isinstance(statement, ir.SetFlag) and statement.name == "i":
                masks = True
            lines.append(printer.statement(statement))
        if lifter.cycles > counted:
            lines.append(f"cpu.cycles += {lifter.cycles - counted};")
        if masks:
            lines.append("m6809_mask_changed();")

        control = lifter.control
        following = instruction.next & 0xFFFF
        if control.kind == "next":
            lines += [f"M6809_CHECK({hex16(following)});", self.transfer(region, key, following)]
        elif control.kind == "goto":
            lines += [f"M6809_CHECK({hex16(control.target)});", self.transfer(region, key, control.target)]
        elif control.kind == "branch":
            extra = lifter.extras.get("taken", 0)
            taken = ([f"cpu.cycles += {extra};"] if extra else []) + \
                [f"M6809_CHECK({hex16(control.target)});", self.transfer(region, key, control.target)]
            lines += [f"if ({printer.expr(control.condition)})", "{"] + [f"\t{line}" for line in taken] + ["}"]
            lines += [f"M6809_CHECK({hex16(following)});", self.transfer(region, key, following)]
        elif control.kind == "call":
            if control.target is not None:
                lines += [f"M6809_CHECK({hex16(control.target)});", f"return {hex16(control.target)};"]
            else:
                lines += [f"{{ const uint32_t target = {printer.expr(control.address)};",
                          "M6809_CHECK(target); return (uint16_t)target; }"]
        elif control.kind in ("jump", "return"):
            lines += [f"{{ const uint32_t target = {printer.expr(control.address)};",
                      "M6809_CHECK(target); return (uint16_t)target; }"]
        elif control.kind == "rti":
            lines += [f"{{ const uint32_t target = {printer.expr(control.address)};",
                      "M6809_CHECK(target); return m6809_rti((uint16_t)target); }"]
        elif control.kind == "wait":
            if lifter.extras.get("cwai"):
                lines += [f"return m6809_cwai({hex16(following)});"]
            else:
                lines += ["m6809_sync();", f"M6809_CHECK({hex16(following)});", self.transfer(region, key, following)]
        else:
            raise ValueError(f"{address:04X}: control {control.kind}")
        return lines

    def region_text(self, region):
        body = self.regions[region]
        lines = [f"uint16_t {name_of(region)}(uint16_t pc)", "{", "\tswitch (pc)", "\t{"]
        for key in body:
            lines.append(f"\tcase {hex16(key[1])}: goto {label_of(key)};")
        lines += ["\tdefault: return m6809_not_code(pc);", "\t}"]
        for key in body:
            instruction = self.instructions[key]
            text = instruction.text.replace("*/", "* /")
            lines.append(f"{label_of(key)}:\t/* {'' if key[0] is None else f'{key[0]}:'}{key[1]:04X}  {text} */")
            lines.append("\t{")
            lines += [f"\t\t{line}" for line in self.instruction_lines(region, key)]
            lines.append("\t}")
        lines.append("}")
        return "\n".join(lines)

    def irq_entry_text(self):
        """The IRQ's entry (lift.IrqEntry) as C: the state pushed, I set, the vector's address given back"""
        printer = Printer()
        entry = lift.IrqEntry(0, prefix="t_")
        # the PC pushed is the function's argument: the lift's constant pushes of 'address' 0 become 'pc's bytes
        lines = ["uint16_t m6809_irq_entry(uint16_t pc)", "{"]
        data = [access for access in entry.accesses if access.kind in ("R", "W")]
        counted, position, pushes = 0, 0, 0
        for statement in entry.statements:
            is_access = isinstance(statement, ir.Store) or (isinstance(statement, ir.SetTemp) and
                                                          isinstance(statement.value, ir.Load))
            if is_access:
                at = data[position].cycle + 1
                position += 1
                if at > counted:
                    lines.append(f"\tcpu.cycles += {at - counted};")
                    counted = at
            text = printer.statement(statement)
            if isinstance(statement, ir.Store) and pushes < 2:
                # the first two pushes are the PC's low and high bytes
                value = "(uint8_t)(pc & 0xFFu)" if pushes == 0 else "(uint8_t)(pc >> 8)"
                text = f"mem_write8({printer.expr(statement.address)}, {value});"
                pushes += 1
            lines.append(f"\t{text}")
            if isinstance(statement, ir.SetTemp) and statement.temp.name.startswith("t_pc"):
                pass
        if entry.cycles > counted:
            lines.append(f"\tcpu.cycles += {entry.cycles - counted};")
        lines.append(f"\treturn (uint16_t)({printer.expr(entry.control.address)});")
        lines.append("}")
        return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[2])
    parser.add_argument("--rom", nargs="*", help="the ROM set's .zips or folder (default: rom/)")
    args = parser.parse_args()
    program, syms, code, ram_code = load_code(args.rom or rom.default_paths(ROOT))
    translator = Translator(code)
    os.makedirs(OUT, exist_ok=True)
    for old in os.listdir(OUT):
        if old.startswith("program_") and old.endswith(".c"):
            os.remove(os.path.join(OUT, old))

    order = lambda k: (-1 if k[0] is None else k[0], k[1])    # noqa: E731
    regions = sorted(translator.regions, key=order)
    prototypes = "\n".join(f"uint16_t {name_of(r)}(uint16_t pc);" for r in regions)
    with open(os.path.join(OUT, "program.h"), "w", encoding="ascii", newline="\n") as out:
        out.write(HEADER + "#ifndef MAKAIMURA_PROGRAM_H\n#define MAKAIMURA_PROGRAM_H\n\n#include <stdint.h>\n\n"
                  + prototypes + "\n\n#endif\n")
    include = '#include "m6809/cpu.h"\n#include "gng/fair_knight.h"\n#include "program.h"\n\n'
    missing = [f"{a:04X}" for a in FAIR_KNIGHT_HOOKS if (None, a) not in translator.instructions]
    if missing:
        print(f"Fair Knight: no instruction at {', '.join(missing)}: not this ROM's program?")
        return 1
    files = 0
    for number, first in enumerate(range(0, len(regions), REGIONS_PER_FILE)):
        texts = [translator.region_text(r) for r in regions[first:first + REGIONS_PER_FILE]]
        if number == 0:
            texts.insert(0, translator.irq_entry_text())
        with open(os.path.join(OUT, f"program_{number:02}.c"), "w", encoding="ascii", newline="\n") as out:
            out.write(HEADER + include + "\n\n".join(texts) + "\n")
        files += 1

    # the dispatch: every instruction's key to its region
    rows = []
    for key in sorted(translator.instructions, key=order):
        bank, address = key
        rows.append(f"\t{{ {-1 if bank is None else bank}, {hex16(address)}, {name_of(translator.owner[key])} }},")
    overlay = ", ".join(f"{{ {hex16(a)}, 0x{v:02X}u }}" for a, v in sorted(ram_code.items()))
    with open(os.path.join(OUT, "entries.c"), "w", encoding="ascii", newline="\n") as out:
        out.write(HEADER + include + "const m6809_entry m6809_entries[] =\n{\n" + "\n".join(rows) + "\n};\n"
                  + f"const unsigned m6809_entry_count = {len(rows)};\n\n"
                  + "/* the RAM the program copies code to: the bytes the translation was made from */\n"
                  + f"const m6809_ram_byte m6809_ram_code[] = {{ {overlay} }};\n"
                  + f"const unsigned m6809_ram_code_count = {len(ram_code)};\n")

    print(f"instructions:   {len(translator.instructions)} in {len(regions)} regions, {files} files")
    print(f"not translated: {len(translator.unsupported)}")
    for key, problem in sorted(translator.unsupported.items(), key=lambda kv: order(kv[0]))[:10]:
        print(f"  {'' if key[0] is None else f'{key[0]}:'}{key[1]:04X}  {problem}")
    print(f"Output: {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
